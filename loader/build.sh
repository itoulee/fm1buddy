#!/bin/sh
# Build the flash loader (build/mflr-loader.bin, and src/app/mflr_loader.h: the same bytes, in the board's program):
# m-bootloader's, MIT, with our screen: rows, the sector map (FC47), the theme's colours (FC49) and the reset (FC48).
# It runs in the FM-1's RAM, where JieLi's wl82loader.bin did, and answers the same commands (src/app/uboot.cpp).
# lilfm1buddy builds it from here too (its third_party/fm1buddy).
#   PI32V2_TOOLCHAIN=~/pi32v2-llvm loader/build.sh
# The toolchain is jvitkauskas/pi32v2-llvm (pi32v2-23.1.5-2: macOS and Linux, x64 and arm64), not JieLi's.
set -e
TC="$(cd "${PI32V2_TOOLCHAIN:?PI32V2_TOOLCHAIN must point at the pi32v2 LLVM toolchain}" && pwd -P)"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT=build
L="$ROOT/loader"
AT=0x1c20000 # its link and entry address: the first of its two slots (0x8000 each)
mkdir -p "$ROOT/$OUT/loader"

CC="$TC/bin/clang"
LD="$TC/bin/ld.lld"
OC="$TC/bin/llvm-objcopy"
FLAGS="-target pi32v2 -mcpu=r3 -std=c99 -Oz -ffreestanding -fno-builtin -fno-common -ffunction-sections -fdata-sections -Wall -Wextra -Werror -I$L/include -DLOADER_ADDRESS=$AT"

for f in core platform display runtime loader loader_target; do
  "$CC" $FLAGS -c "$L/src/$f.c" -o "$ROOT/$OUT/loader/$f.o"
done
"$CC" -E -P -x c -DENTRY_SYMBOL=loader_entry -DRAM_ORIGIN=$AT -DRAM_LENGTH=0x8000 -DLOADER_BUILD "$L/tools/target.ld.S" \
  -o "$ROOT/$OUT/loader/target.ld"
"$LD" --plugin-opt=O3 --relax --gc-sections -T "$ROOT/$OUT/loader/target.ld" -Map "$ROOT/$OUT/loader/loader.map" \
  -o "$ROOT/$OUT/loader/loader.elf" "$ROOT/$OUT/loader"/*.o
"$OC" -O binary -j .text "$ROOT/$OUT/loader/loader.elf" "$ROOT/$OUT/mflr-loader.bin"

n=$(wc -c <"$ROOT/$OUT/mflr-loader.bin")
[ "$n" -le 32768 ] || { echo "mflr-loader.bin: $n bytes: it doesn't fit its 0x8000 slot" >&2; exit 1; }
echo "mflr-loader.bin: $n bytes (at $AT)"

# the board has it in its program (nothing to download, no Wi-Fi), so rebuild it into it
python3 - "$ROOT/$OUT/mflr-loader.bin" "$L/../src/app/mflr_loader.h" <<'EOF'
import sys
data = open(sys.argv[1], 'rb').read()
out = ['// Generated by loader/build.sh from build/mflr-loader.bin: m-bootloader\'s flash loader (MIT, loader/), with the',
       '// sector map. It runs in the FM-1\'s boot ROM\'s place. Don\'t edit: run loader/build.sh.', '',
       '// clang-format off', '#pragma once', '#include <stdint.h>', '',
       'static const uint8_t MFLR_LOADER[] = {']
for i in range(0, len(data), 16):
    out.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 16]) + ',')
out.append('};')
out.append('static const uint32_t MFLR_LOADER_LEN = %d;' % len(data))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
EOF
echo "src/app/mflr_loader.h: the same, in the board's program"
